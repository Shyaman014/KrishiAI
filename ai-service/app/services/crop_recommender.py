"""
Crop Recommendation Service – KrishiAI Phase 10.

Loads the trained RandomForest model from checkpoints and provides
top-3 crop predictions with supporting factor explanations.

DISCLAIMER: All predictions are based on training data patterns derived
from synthetic agronomic ranges. Never treat confidence scores as a
guarantee of agricultural suitability. Always verify with local experts.
"""

from __future__ import annotations

import json
import logging
from functools import lru_cache
from pathlib import Path
from typing import Any

import joblib
import numpy as np

from app.training.crop_data import CROP_DETAILS, FEATURE_NAMES

logger = logging.getLogger(__name__)

CHECKPOINT_DIR = Path(__file__).resolve().parents[2] / "checkpoints" / "crop_recommender"

DISCLAIMER = (
    "These recommendations are generated by a machine learning model trained on "
    "synthetic agronomic data. They are intended as a starting point only. "
    "Actual suitability depends on local soil conditions, microclimate, market access, "
    "and other factors. Please consult a local agricultural expert (KVK / ICAR) "
    "before making farming decisions."
)


class CropRecommenderNotReadyError(RuntimeError):
    """Raised when the model checkpoint is not found."""


class CropRecommender:
    """Random Forest-based crop recommendation engine."""

    def __init__(self) -> None:
        self._model: Any = None
        self._label_encoder: Any = None
        self._feature_names: list[str] = FEATURE_NAMES
        self._metadata: dict[str, Any] = {}
        self._loaded = False

    def load(self) -> None:
        """Load model checkpoint from disk. Call once at startup."""
        model_path = CHECKPOINT_DIR / "model.pkl"
        le_path = CHECKPOINT_DIR / "label_encoder.pkl"
        features_path = CHECKPOINT_DIR / "feature_names.pkl"
        metadata_path = CHECKPOINT_DIR / "model_metadata.json"

        if not model_path.exists():
            raise CropRecommenderNotReadyError(
                f"Crop recommendation model not found at '{model_path}'. "
                "Run 'python -m app.training.train_crop_recommender' first."
            )

        self._model = joblib.load(model_path)
        self._label_encoder = joblib.load(le_path)
        if features_path.exists():
            self._feature_names = joblib.load(features_path)
        if metadata_path.exists():
            with open(metadata_path, encoding="utf-8") as f:
                self._metadata = json.load(f)
        self._loaded = True
        logger.info(
            "CropRecommender loaded. Version=%s, classes=%d",
            self._metadata.get("model_version", "unknown"),
            len(self._label_encoder.classes_),
        )

    @property
    def model_version(self) -> str:
        return self._metadata.get("model_version", "1.0.0")

    @property
    def is_loaded(self) -> bool:
        return self._loaded

    # ------------------------------------------------------------------
    # Core prediction
    # ------------------------------------------------------------------

    def predict_top3(
        self,
        N: float,
        P: float,
        K: float,
        temperature: float,
        humidity: float,
        ph: float,
        rainfall: float,
    ) -> list[dict[str, Any]]:
        """Return top-3 crop recommendations with confidence and supporting factors.

        Args:
            N:           Nitrogen content (kg/ha)
            P:           Phosphorus content (kg/ha)
            K:           Potassium content (kg/ha)
            temperature: Mean temperature (°C)
            humidity:    Relative humidity (%)
            ph:          Soil pH
            rainfall:    Annual rainfall (mm)

        Returns:
            List of dicts with keys: rank, crop, confidence, supporting_factors,
            crop_details, disclaimer.
        """
        if not self._loaded:
            raise CropRecommenderNotReadyError("CropRecommender not loaded. Call load() first.")

        features = np.array(
            [[N, P, K, temperature, humidity, ph, rainfall]], dtype=np.float32
        )

        # Probabilities for all classes
        proba = self._model.predict_proba(features)[0]
        classes = self._label_encoder.classes_

        # Top-3 indices by descending probability
        top_indices = np.argsort(proba)[::-1][:3]

        # Feature importances from the trained forest
        feature_importances = self._model.feature_importances_
        input_values = {
            "N": N,
            "P": P,
            "K": K,
            "temperature": temperature,
            "humidity": humidity,
            "ph": ph,
            "rainfall": rainfall,
        }

        results = []
        for rank, idx in enumerate(top_indices, start=1):
            crop_name = str(classes[idx])
            confidence = float(round(float(proba[idx]), 4))
            supporting_factors = self._build_supporting_factors(
                crop_name, feature_importances, input_values
            )
            details = CROP_DETAILS.get(crop_name, {})
            results.append(
                {
                    "rank": rank,
                    "crop": crop_name,
                    "confidence": confidence,
                    "confidence_pct": round(confidence * 100, 1),
                    "supporting_factors": supporting_factors,
                    "growing_duration": details.get("growing_duration", "Varies"),
                    "water_requirement": details.get("water_requirement", "Varies"),
                    "suitable_season": details.get("suitable_season", "Varies"),
                    "soil_requirement": details.get("soil_requirement", "Varies"),
                    "description": details.get("description", ""),
                    "source": details.get("source", "ICAR / FAO"),
                    "disclaimer": DISCLAIMER,
                }
            )

        return results

    # ------------------------------------------------------------------
    # Supporting factor builder
    # ------------------------------------------------------------------

    def _build_supporting_factors(
        self,
        crop: str,
        feature_importances: np.ndarray,
        input_values: dict[str, float],
    ) -> list[dict[str, str]]:
        """Generate human-readable explanation of key agronomic factors."""
        # Sort features by importance (descending), pick top-4
        ranked = sorted(
            zip(self._feature_names, feature_importances, [input_values[f] for f in self._feature_names]),
            key=lambda x: x[1],
            reverse=True,
        )[:4]

        factor_labels = {
            "N": ("Nitrogen", "kg/ha"),
            "P": ("Phosphorus", "kg/ha"),
            "K": ("Potassium", "kg/ha"),
            "temperature": ("Temperature", "°C"),
            "humidity": ("Humidity", "%"),
            "ph": ("Soil pH", ""),
            "rainfall": ("Annual Rainfall", "mm"),
        }

        factors = []
        for feature, importance, value in ranked:
            label, unit = factor_labels.get(feature, (feature, ""))
            value_str = f"{value:.1f}{' ' + unit if unit else ''}"
            factors.append(
                {
                    "factor": label,
                    "value": value_str,
                    "importance_pct": f"{importance * 100:.1f}%",
                    "explanation": self._factor_explanation(feature, value, crop),
                }
            )
        return factors

    def _factor_explanation(self, feature: str, value: float, crop: str) -> str:
        """Return a plain-language explanation for a feature value."""
        explanations: dict[str, list[tuple[tuple[float, float], str]]] = {
            "N": [
                ((0, 30), "Low nitrogen – suitable for legumes that fix their own nitrogen."),
                ((30, 80), "Moderate nitrogen – supports moderate-feeder crops."),
                ((80, 200), "High nitrogen – benefits heavy feeders like rice and maize."),
            ],
            "P": [
                ((0, 30), "Low phosphorus – suited to crops with minimal P demand."),
                ((30, 80), "Moderate phosphorus – supports root and flower development."),
                ((80, 200), "High phosphorus – ideal for root crops and high-yielding varieties."),
            ],
            "K": [
                ((0, 30), "Low potassium – suited to crops with low K demand."),
                ((30, 80), "Moderate potassium – supports disease resistance and water uptake."),
                ((80, 200), "High potassium – benefits fruit crops and stress-tolerant varieties."),
            ],
            "temperature": [
                ((0, 15), "Cool temperature – suitable for temperate/Rabi crops."),
                ((15, 25), "Mild temperature – broad range of crops can thrive."),
                ((25, 35), "Warm temperature – favours tropical and Kharif crops."),
                ((35, 50), "Hot temperature – only heat-tolerant crops recommended."),
            ],
            "humidity": [
                ((0, 40), "Low humidity – suited to drought-tolerant crops."),
                ((40, 70), "Moderate humidity – supports most field crops."),
                ((70, 100), "High humidity – favours tropical crops; monitor for disease."),
            ],
            "ph": [
                ((0, 5.5), "Acidic soil – limited crop range; lime application may help."),
                ((5.5, 7.0), "Slightly acidic to neutral – optimal for most crops."),
                ((7.0, 8.0), "Mildly alkaline – suitable for legumes and most cereals."),
                ((8.0, 14), "Alkaline soil – restricts crop choice; gypsum may help."),
            ],
            "rainfall": [
                ((0, 60), "Low rainfall – drought-tolerant crops recommended."),
                ((60, 150), "Moderate rainfall – supports most field and horticultural crops."),
                ((150, 400), "High rainfall – tropical and water-intensive crops suitable."),
            ],
        }
        for (lo, hi), text in explanations.get(feature, []):
            if lo <= value < hi:
                return text
        return f"Value of {value:.1f} is within the recorded range for {crop}."


# ---------------------------------------------------------------------------
# Module-level singleton (lazy-loaded on first use by the router)
# ---------------------------------------------------------------------------

@lru_cache(maxsize=1)
def get_crop_recommender() -> CropRecommender:
    """Return the shared CropRecommender instance (loaded on first call)."""
    recommender = CropRecommender()
    recommender.load()
    return recommender

